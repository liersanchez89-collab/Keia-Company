-- ── Proyectos ──
create table if not exists projects (
  id bigint generated by default as identity primary key,
  name text not null, color text, light text, clockify_id text,
  created_at timestamptz default now()
);

-- ── Facturas (ingresos y gastos) ──
create table if not exists facturas (
  id bigint generated by default as identity primary key,
  tipo text,            -- 'ingreso' | 'gasto'
  estado text default 'aprobada',   -- 'pendiente' | 'aprobada'
  proyecto text, fecha text, base text, iva text, total text, ref text,
  descripcion text, link_factura text, reparto text, pagado boolean default false,
  frc_sign text default '+',
  created_at timestamptz default now()
);

-- ── Hojas de gasto (tickets sin factura) ──
create table if not exists hojas_gasto (
  id bigint generated by default as identity primary key,
  fecha text, link text, importe text, responsable text, proyecto text,
  reparto text, pagado boolean default false, importe_proyecto text, proyectos text,
  created_at timestamptz default now()
);
create table if not exists solicitudes_hoja_gasto (
  id bigint generated by default as identity primary key,
  nombre_archivo text, url text, path text, estado text default 'pendiente', datos text,
  created_at timestamptz default now()
);

-- ── Checkpoints: bookpoints y customers ──
create table if not exists bookpoints (
  id bigint primary key, member text, grupo text, autor text, libro text, topic text,
  puntos text, fecha text, essay text, "linkMotorola" text, cc text
);
create table if not exists customers (
  id bigint primary key, member text, grupo text, fecha text, cat text, motorola text,
  quien text, cliente text, "linkMotorola" text, proyecto text, companeros text,
  linked_from bigint, linked_owner text
);
create table if not exists groups_bp (id text primary key, name text);
create table if not exists groups_cv (id text primary key, name text);

-- ── CRM ──
create table if not exists crm (
  id text primary key, proyecto text, grupo_key text, grupo_name text, cliente text,
  ubicacion text, tlf text, email text, estado text, comentarios text
);

-- ── Calendario, actas y chat ──
create table if not exists calendario (
  id text primary key, titulo text, descripcion text, fecha text, prioridad text,
  estado text, proyecto text, responsable text
);
create table if not exists actas (
  id text primary key, titulo text, fecha text, asistentes text, proyectos text,
  decisiones text, tareas text
);
create table if not exists chat_messages (
  id bigint generated by default as identity primary key,
  grupo text, autor text, texto text, created_at timestamptz default now()
);

-- ── Previsiones ──
create table if not exists presupuestos_2026 (
  proyecto text not null, mes integer not null, ing_est numeric default 0, gas_est numeric default 0,
  primary key (proyecto, mes)
);
create table if not exists presupuestos_activos (proyecto text primary key);

-- ── Estrategia / roles / evaluaciones ──
create table if not exists estrategia (key text primary key, val jsonb);
create table if not exists estrategia_activos (proyecto text primary key);
create table if not exists proyecto_roles (
  proyecto text not null, miembro text not null, rol text, primary key (proyecto, miembro)
);
create table if not exists evaluaciones_members (idx integer primary key, name text, role text);
create table if not exists evaluaciones_scores (
  key text primary key, team_score numeric, color text, comment text, member_scores jsonb
);
create table if not exists member_colors (name text primary key, color text);

-- ── Ajustes guardados como clave/valor (horas, auditorías, MTA, diamante…) ──
create table if not exists audit_progress (key text primary key, val jsonb);
create table if not exists mta_progress (key text primary key, val jsonb);
create table if not exists diamante (id text primary key, val jsonb);
create table if not exists horas_proyecto (id text primary key, val jsonb);

-- ── Permisos: la app entra con la "anon key" (igual que el original) ──
do $$
declare t text;
begin
  foreach t in array array['projects','facturas','hojas_gasto','solicitudes_hoja_gasto','bookpoints','customers',
    'groups_bp','groups_cv','crm','calendario','actas','chat_messages','presupuestos_2026','presupuestos_activos',
    'estrategia','estrategia_activos','proyecto_roles','evaluaciones_members','evaluaciones_scores','member_colors',
    'audit_progress','mta_progress','diamante','horas_proyecto']
  loop
    execute format('alter table %I enable row level security', t);
    execute format('drop policy if exists "acceso app" on %I', t);
    execute format('create policy "acceso app" on %I for all using (true) with check (true)', t);
  end loop;
end $$;

-- ── Tiempo real (cambios al momento entre personas) ──
alter publication supabase_realtime add table facturas, calendario, customers, solicitudes_hoja_gasto, audit_progress, chat_messages;

-- ── Almacenamiento de archivos (tickets, hojas de gasto, extractos del banco) ──
insert into storage.buckets (id, name, public) values ('hoja_gasto','hoja_gasto', true)
  on conflict (id) do nothing;
drop policy if exists "hoja_gasto leer" on storage.objects;
drop policy if exists "hoja_gasto subir" on storage.objects;
drop policy if exists "hoja_gasto cambiar" on storage.objects;
drop policy if exists "hoja_gasto borrar" on storage.objects;
create policy "hoja_gasto leer"    on storage.objects for select using (bucket_id = 'hoja_gasto');
create policy "hoja_gasto subir"   on storage.objects for insert with check (bucket_id = 'hoja_gasto');
create policy "hoja_gasto cambiar" on storage.objects for update using (bucket_id = 'hoja_gasto');
create policy "hoja_gasto borrar"  on storage.objects for delete using (bucket_id = 'hoja_gasto');
